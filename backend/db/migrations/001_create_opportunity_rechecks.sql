CREATE TABLE IF NOT EXISTS opportunity_rechecks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id CHAR(24) NOT NULL
    CHECK (opportunity_id ~ '^[a-fA-F0-9]{24}$'),
  last_checked DATE NOT NULL,
  rechecked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS opportunity_rechecks_opportunity_id_idx
  ON opportunity_rechecks (opportunity_id, rechecked_at DESC);
